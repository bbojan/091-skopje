export type Lang = keyof typeof STR;
/** Every UI text key (English has them all). */
export type Key = keyof typeof STR.en;
type Dict = Partial<Record<Key, string>>;
// compile-time completeness check: every translation has every key English has
// (Macedonian only holds the JavaScript-set strings; the rest is in index.html)
STR satisfies { [L in Exclude<Lang, 'mk'>]: Record<Key, string> } & { mk: Dict };

const isLang = (s: string | null): s is Lang => !!s && s in STR;

// browser languages that map onto ours (Bosnian → Croatian Latin, Montenegrin → Serbian)
const ALIAS: Record<string, Lang> = { mk: 'mk', en: 'en', sr: 'sr', cnr: 'sr', sh: 'sr', hr: 'hr', bs: 'hr', sl: 'sl', sq: 'sq' };

function detect(): Lang {
  const q = new URLSearchParams(location.search).get('lang');
  if (isLang(q)) return q;
  try { const s = localStorage.getItem('skopje.lang'); if (isLang(s)) return s; } catch { /* storage unavailable */ }
  // first regional language the browser asks for; otherwise Macedonian (English is a
  // manual choice, many local browsers are set to en-US)
  for (const l of navigator.languages || [navigator.language]) {
    const c = ALIAS[String(l).toLowerCase().split('-')[0]];
    if (c && c !== 'en') return c;
  }
  return 'mk';
}

