export type Lang = keyof typeof STR;
/** Every UI text key (English has them all). */
export type Key = keyof typeof STR.en;
type Dict = Partial<Record<Key, string>>;
// compile-time completeness check: every translation has every key English has
// (Macedonian only holds the JavaScript-set strings; the rest is in index.html)
STR satisfies { [L in Exclude<Lang, 'mk'>]: Record<Key, string> } & { mk: Dict };

const isLang = (s: string | null): s is Lang => !!s && s in STR;

// browser languages that map onto ours (Bosnian → Croatian Latin, Montenegrin → Serbian)
const ALIAS: Record<string, Lang> = { mk: 'mk', en: 'en', sr: 'sr', cnr: 'sr', sh: 'sr', hr: 'hr', bs: 'hr', sl: 'sl', sq: 'sq' };

function detect(): Lang {
  const q = new URLSearchParams(location.search).get('lang');
  if (isLang(q)) return q;
  try { const s = localStorage.getItem('skopje.lang'); if (isLang(s)) return s; } catch { /* storage unavailable */ }
  // first regional language the browser asks for; otherwise Macedonian (English is a
  // manual choice, many local browsers are set to en-US)
  for (const l of navigator.languages || [navigator.language]) {
    const c = ALIAS[String(l).toLowerCase().split('-')[0]];
    if (c && c !== 'en') return c;
  }
  return 'mk';
}

export let lang: Lang = detect();
const listeners: ((code: Lang) => void)[] = [];
// element → its Macedonian text/attributes from index.html
const orig = new Map<HTMLElement, { html: string; title: string | null; aria: string | null }>();

export function t(key: Key, vars?: Record<string, string>): string {
  let s = (STR[lang] as Dict)[key] ?? (STR.mk as Dict)[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '');
  return s;
}

export function applyI18n(root: ParentNode = document): void {
  document.documentElement.lang = lang;
  const dict = STR[lang] as Record<string, string>;
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n], [data-i18n-title], [data-i18n-aria]')) {
    if (!orig.has(el)) orig.set(el, { html: el.innerHTML, title: el.getAttribute('title'), aria: el.getAttribute('aria-label') });
    const o = orig.get(el)!, d = el.dataset;
    if (d.i18n) el.innerHTML = (lang !== 'mk' && dict[d.i18n]) || o.html;
    if (d.i18nTitle) el.title = (lang !== 'mk' && dict[d.i18nTitle]) || o.title || '';
    if (d.i18nAria) el.setAttribute('aria-label', (lang !== 'mk' && dict[d.i18nAria]) || o.aria || '');
  }
}

export function setLang(code: string): void {
  if (!isLang(code) || code === lang) return;
  lang = code;
  try { localStorage.setItem('skopje.lang', code); } catch { /* storage unavailable */ }
  applyI18n();
  listeners.forEach((f) => f(code));
}

export const onLangChange = (f: (code: Lang) => void): void => { listeners.push(f); };
