// element → its Macedonian text/attributes from index.html
const orig = new Map<HTMLElement, { html: string; title: string | null; aria: string | null }>();

export function t(key: Key, vars?: Record<string, string>): string {
  let s = (STR[lang] as Dict)[key] ?? (STR.mk as Dict)[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '');
  return s;
}

export function applyI18n(root: ParentNode = document): void {
  document.documentElement.lang = lang;
  const dict = STR[lang] as Record<string, string>;
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n], [data-i18n-title], [data-i18n-aria]')) {
    if (!orig.has(el)) orig.set(el, { html: el.innerHTML, title: el.getAttribute('title'), aria: el.getAttribute('aria-label') });
    const o = orig.get(el)!, d = el.dataset;
    if (d.i18n) el.innerHTML = (lang !== 'mk' && dict[d.i18n]) || o.html;
    if (d.i18nTitle) el.title = (lang !== 'mk' && dict[d.i18nTitle]) || o.title || '';
    if (d.i18nAria) el.setAttribute('aria-label', (lang !== 'mk' && dict[d.i18nAria]) || o.aria || '');
  }
}

export function setLang(code: string): void {
  if (!isLang(code) || code === lang) return;
  lang = code;
  try { localStorage.setItem('skopje.lang', code); } catch { /* storage unavailable */ }
  applyI18n();
  listeners.forEach((f) => f(code));
}

export const onLangChange = (f: (code: Lang) => void): void => { listeners.push(f); };
